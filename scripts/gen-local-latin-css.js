#!/usr/bin/env node
/**
 * Generate fonts/latin-fonts.local.css for the full-offline build.
 *
 * The app, and every standalone export, only uses Cardo and Source Serif 4 as
 * committed TTFs. Lora / Merriweather / Open Sans / Roboto are pickable in the
 * editor font list, but exports already fall back to system fonts for them, and
 * `style.css` styles UI chrome with the system stack — so no gfont-*.woff2
 * slices are shipped (or committed) any more.
 *
 * Output keeps the family names (a saved fontStack still resolves) but pulls
 * local families from TTFs only.
 *
 * Usage: node scripts/gen-local-latin-css.js   (also run by build-targets.js)
 */
'use strict';

const fs = require('fs');
const path = require('path');

const FONTS = path.resolve(__dirname, '..', 'fonts');

// family → local TTF files (same files app-fonts.css registers)
const LOCAL_TTF = {
  'Cardo': [{ file: 'Cardo-Regular.ttf', weight: '400 700', style: 'normal' }],
  'Source Serif 4': [
    { file: 'SourceSerif4-Regular.ttf', weight: '400', style: 'normal' },
    { file: 'SourceSerif4-Bold.ttf', weight: '700', style: 'normal' },
    { file: 'SourceSerif4-Italic.ttf', weight: '400', style: 'italic' },
    { file: 'SourceSerif4-BoldItalic.ttf', weight: '700', style: 'italic' }
  ]
};

// Families with no local file: keep the name alive via the system font.
const SYSTEM_ONLY = {
  'Lora': { weights: ['400', '700'] },
  'Merriweather': { weights: ['400', '700'] },
  'Open Sans': { weights: ['400', '700'] },
  'Roboto': { weights: ['400', '500', '700'] }
};

const out = [`/* GENERATED by scripts/gen-local-latin-css.js — do not edit by hand.
 * Full-offline build: Cardo / Source Serif 4 come from local TTFs, the other
 * families resolve to the installed system font. No woff2 slices are shipped. */
`];

// Try the real font first, then plain Georgia/serif look-alikes.
for (const [family, spec] of Object.entries(SYSTEM_ONLY)) {
  const looks = family === 'Open Sans' || family === 'Roboto' ? 'Arial' : 'Georgia';
  for (const weight of spec.weights) {
    out.push(`@font-face {
  font-family: '${family}';
  font-style: normal;
  font-weight: ${weight};
  font-display: swap;
  src: local('${family}'), local('${looks}');
}`);
  }
}

for (const [family, faces] of Object.entries(LOCAL_TTF)) {
  for (const face of faces) {
    const data = fs.readFileSync(path.join(FONTS, face.file)).toString('base64');
    out.push(`/* ${face.file} */
@font-face {
  font-family: '${family}';
  font-style: ${face.style};
  font-weight: ${face.weight};
  font-display: swap;
  src: url(data:font/ttf;base64,${data}) format('truetype');
}`);
  }
}

fs.writeFileSync(path.join(FONTS, 'latin-fonts.local.css'), `${out.join('\n\n')}\n`, 'utf8');
console.log(`latin-fonts.local.css: ${Object.keys(LOCAL_TTF).length} local families, ${Object.keys(SYSTEM_ONLY).length} system fallbacks`);
